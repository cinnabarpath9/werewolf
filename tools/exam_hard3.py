def class_counts(bank: list[Q]) -> dict[str, int]:
    """按类别数题（本批只有「局势」一类，保持与 exam_hard2 同名的接口）。"""
    n: dict[str, int] = {}
    for q in bank:
        n[q.category] = n.get(q.category, 0) + 1
    return n


def sources(bank: list[Q]) -> dict[str, str]:
    """题号 → 取材来源 URL（闸门与报告都用它）。"""
    return {q.qid: str(getattr(q, "source", "")) for q in bank}


