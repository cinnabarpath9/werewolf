def _j_rubric(*items) -> list:
    """校验一条 rubric 的写法（与第二批 J 类同一口径：恰好 5 个要点、写法完整、关键词不重复）。"""
    out = [(str(n), [str(w) for w in ws]) for n, ws in items]
    if len(out) != J_POINTS:
        raise ValueError(f"J2 类每题必须恰好 {J_POINTS} 个要点，实际 {len(out)} 个")
    words: list[str] = []
    for name, ws in out:
        if not name.strip() or not ws or any(not w.strip() for w in ws):
            raise ValueError(f"要点「{name}」的写法不完整（名字/关键词不许为空）")
        for w in ws:
            if len(w) < 2:
                raise ValueError(f"要点「{name}」里的关键词「{w}」太短（会被蒙到）")
            if w in words:
                raise ValueError(f"关键词「{w}」在两个要点里重复了（命中会算两次）")
            words.append(w)
    return out


def _j2(qid: str, scenario: str, ask: str, expect: str, *, rubric, forbid, why: str,
        source: str, ledger: dict, tags=(), trap: str = "", giveaways=(),
        negatives=()) -> Q:
    """造一道 J2 题（信息模糊的判断题），并把闸门要用的元信息挂在 Q 上。

    额外挂的属性：
      · `scenario`/`ask`  —— 题面拆两段（局面 / 问句）；
      · `source`          —— **本题局面取自哪一篇真实复盘**（URL）；
      · `book`            —— 本批一律 `closed`：题面只用通用规则，不附规则书/记录；
      · `mechanic`        —— 本批一律 `通用`（不依赖本项目房规）；
      · `trap`            —— 预计模型会踩的坑；
      · `giveaways`       —— 不许出现在 `scenario` 里的「答案字样」；
      · `negatives`       —— **每个要点一条同义改述的反例**（闸门用它证明
                             「要点不是靠碰词」：反例里一个命中词都不出现，必须判错）；
      · `ledger`          —— **人数账**（闸门第二条新增闸门就用它）：
                             `{"board": 12, "alive": [...], "night": [...], "exile": [...]}`
                             —— 板子总人数 = 活着 + 夜里出局 + 被放逐；同一个人**不许**
                             既被夜刀又被放逐（2026-10-13 加：J203/J208 就栽在这上面）。
    """
    rub = _j_rubric(*rubric)
    negs = [str(x) for x in negatives]
    if len(negs) != J_POINTS:
        raise ValueError(f"{qid}：negatives 必须恰好 {J_POINTS} 条（每个要点一条反例），"
                         f"实际 {len(negs)} 条")
    for i, (neg, (_name, ws)) in enumerate(zip(negs, rub), 1):
        if not neg.strip():
            raise ValueError(f"{qid} 第 {i} 条反例是空的")
        for w in ws:
            if w in neg:
                raise ValueError(f"{qid} 第 {i} 条反例里出现了本要点的命中词「{w}」"
                                 "（那就不叫反例了）")
    led = _j_ledger(qid, ledger)
    q = Q(qid=qid, category="局势", question=_full(scenario) + "\n" + ask,
          expect=str(expect), why=why, grader="rubric",
          context="",                        # 空 = 闭卷（exam.py 会给占位上下文，见模块头注释）
          legal=[], forbid=list(forbid),
          rubric=rub, min_points=J_NEED, tags=list(tags),
          board=None, engine_checked=False)
    q.scenario = scenario
    q.ask = ask
    q.source = str(source)
    q.book = "closed"
    q.mechanic = "通用"
    q.trap = str(trap)
    q.giveaways = list(giveaways)
    q.negatives = negs
    q.ledger = led
    return q


def _j_ledger(qid: str, ledger: dict) -> dict:
    """校验并规范一道题的**人数账**（闸门「人数自洽」用的那份元数据）。

    判据（2026-10-13 加）：
      ① 板子总人数 = 活着 + 夜里出局 + 被放逐（三份名单正好把 1…总人数 分完，不重不漏）；
      ② 同一个人**不许**既被夜刀又被放逐（J203 原来就是 2 号既挨刀又被投出去）；
      ③ 活着的人不许出现在出局名单里。
    """
    need = ("board", "alive", "night", "exile")
    led = dict(ledger or {})
    if sorted(led) != sorted(need):
        raise ValueError(f"{qid}：ledger 必须恰好有 {need} 四个字段，实际 {sorted(led)}")
    board = int(led["board"])
    alive = [int(x) for x in led["alive"]]
    night = [int(x) for x in led["night"]]
    exile = [int(x) for x in led["exile"]]
    allseats = set(range(1, board + 1))
    if len(alive) + len(night) + len(exile) != board:
        raise ValueError(f"{qid}：人数账算不平 —— 板子 {board} 人，但活着 {len(alive)} + "
                         f"夜里出局 {len(night)} + 被放逐 {len(exile)} = "
                         f"{len(alive) + len(night) + len(exile)}")
    if set(alive) | set(night) | set(exile) != allseats:
        raise ValueError(f"{qid}：名单没把 1~{board} 号分完（缺 "
                         f"{sorted(allseats - (set(alive) | set(night) | set(exile)))}、"
                         f"多 {sorted((set(alive) | set(night) | set(exile)) - allseats)}）")
    both = sorted(set(night) & set(exile))
    if both:
        raise ValueError(f"{qid}：{both} 既被夜刀又被放逐（同一个人不能死两次）")
    dup_alive = sorted(set(alive) & (set(night) | set(exile)))
    if dup_alive:
        raise ValueError(f"{qid}：{dup_alive} 同时在活着名单和出局名单里")
    if len(set(alive)) != len(alive) or len(set(night)) != len(night) \
            or len(set(exile)) != len(exile):
        raise ValueError(f"{qid}：名单里有重复的座位号")
    return {"board": board, "alive": alive, "night": night, "exile": exile}


