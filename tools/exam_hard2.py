def _q(qid: str, category: str, scenario: str, ask: str, expect: str = "", *,
       grader: str = "exact", legal=None, forbid=None, rubric=None, min_points: int = 0,
       board: str | None = None, book: str = "open", mechanic: str = "特设",
       why: str = "", tags=(), giveaways=(), trap: str = "", recheck=None) -> Q:
    """造一道第二批难题，并把闸门要用的元信息挂在 Q 上。

    除了 `Q` 自己的字段，额外挂这几个（dataclass 允许调用方挂属性）：
      · `scenario` / `ask`  —— 题面拆两段（局面 / 问句）：反饱和检查只查局面那一段；
      · `book`              —— open = 答案依赖本项目特设口径（必须附 `rules:` 公告）；
                               closed = 只用官方机制（公告照附，只为与游戏内一致）；
      · `mechanic`          —— 特设 / 官方（写报告用）；
      · `giveaways`         —— 明确不许出现在 `scenario` 里的「答案字样」；
      · `trap`              —— **预计模型会踩的坑**（哪个官方印象 / 哪一步算错）；
                               闸门要求每题都写，报告里的「为什么能分档」直接取它；
      · `recheck`           —— 重算入口（R 类必须给，闸门会抽题重跑引擎）。
    """
    q = Q(qid=qid, category=category, question=scenario + "\n" + ask,
          expect=str(expect), why=why, grader=grader,
          context=f"rules:{board or J_BOARD}", legal=list(legal or []),
          forbid=list(forbid or []), rubric=[(str(n), [str(w) for w in ws])
                                             for n, ws in (rubric or [])],
          min_points=int(min_points or 0), tags=list(tags),
          board=board or J_BOARD, engine_checked=True)
    q.scenario = scenario
    q.ask = ask
    q.book = book
    q.mechanic = mechanic
    q.giveaways = list(giveaways)
    q.trap = str(trap)
    q.recheck = recheck
    VERIFIED.add(qid)
    if recheck is not None:
        R_RECHECK[qid] = recheck
    return q


def _by_day(table: dict):
    """剧本表按「第几天」分派（引擎每次调用都会 set_context(day, kind)）。"""
    def reply(seat_id, task, day=1):
        keys = sorted(table)
        return dict(table.get(day if day in table else keys[-1]) or {})
    return reply


