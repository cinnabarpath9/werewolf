#: J 类的要点数下限（每道题 5 个要点、命中 3 个算对 —— 见 `_J_NEED`）。
J_POINTS = 5
J_NEED = math.ceil(J_POINTS * 0.6)


def _j_rubric(*items) -> list:
    """校验一条 rubric 的写法：必须 5 个要点、每个要点名和关键词都非空、关键词不重复。"""
    out = [(str(n), [str(w) for w in ws]) for n, ws in items]
    if len(out) != J_POINTS:
        raise ValueError(f"J 类每题必须恰好 {J_POINTS} 个要点，实际 {len(out)} 个")
    words: list[str] = []
    for name, ws in out:
        if not name.strip() or not ws or any(not w.strip() for w in ws):
            raise ValueError(f"要点「{name}」的写法不完整（名字/关键词不许为空）")
        for w in ws:
            if len(w) < 2:
                raise ValueError(f"要点「{name}」里的关键词「{w}」太短（会被蒙到）")
            if w in words:
                raise ValueError(f"关键词「{w}」在两个要点里重复了（命中会算两次）")
            words.append(w)
    return out


