def _heads(g) -> tuple[int, int]:
    """引擎口径的（神边人头数, 民边人头数）—— 愚者两边都算，直接用 `_sides`。"""
    gods, vils = _sides(g)
    return len(gods), len(vils)


def _night(alive, day: int, *, board: str = J_BOARD, roles=None, **script):
    """真跑一夜（含结算），返回 `(引擎局, 死者列表)`。

    ⚠️ 两个坑（第一版就踩到了，闸门把它们抓了出来）：
      1) `night()` **只返回**死者列表、**不把死者落到座位上** —— 那一步在白天流程里做。
         所以这里必须自己 `kill()` 一遍，否则后面数人头会看到「一个人都没死」。
      2) 狼队的刀口同时受 `wolf_intent`（决策在前）和 `wolf_kill` 控制，
         只改 `wolf_kill` 会被默认意图覆盖 —— 钉刀口请用 `_knife()`。
    """
    g = _game(board, roles or KING_SEATS, alive=alive, script=_script(**script), log=[],
              wolf_control=False)
    g.day = day
    g.phase = "night"
    deaths = _run_blocking(g.night())
    for _sid, _cause in deaths:
        g.kill(_sid, _cause)
    return g, deaths


def _apply_deaths(g, deaths) -> None:
    """把 `night()` 返回的死者真正落到座位上（引擎里这一步由白天流程做）。"""
    for _sid, _cause in deaths:
        g.kill(_sid, _cause)


def _knife(target: int) -> dict:
    """把狼队今晚的刀口钉死：`wolf_intent`（决策在前）与 `wolf_kill` 都要写。"""
    return {"wolf_intent": {"*": {"target": target, "reason": "剧本"}},
            "wolf_talk": {"*": {"speech": "（剧本）", "target": target}},
            "wolf_kill": {"*": {"target": target, "reason": "剧本"}}}


def _king_last_bite(g, _take: int) -> bool:
    """狼王夜里出局时真跑他那一口（剧本里写了他带走谁）；他没死就返回 False。"""
    king = g.seat_by_id(4)
    if king.alive:
        return False
    _run_blocking(g.wolf_king_take(king, where="剧本：你夜里出局了", daytime=False))
    return not g.seat_by_id(_take).alive


def _score_heads(gods: int, vils: int) -> int:
    """Z201 的收益函数：两边都还剩 ≥2 张 = 3 分（还守得住）；一边只剩 1 张 = 1 分；
    两边都只剩 1 张（下一夜必被屠边）= 0 分。"""
    return 3 if min(gods, vils) >= 2 else (1 if max(gods, vils) >= 2 else 0)


def _fmt_pairs(pairs) -> str:
    """把 `{标签: 值}` 排成人话（**不用 dict 的 repr** —— 那会带出 ASCII 单引号，
    混在中文里正好踩本项目「中文只用「」」那条闸门）。"""
    return "；".join(f"{k} = {v}" for k, v in pairs)


