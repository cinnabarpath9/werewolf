#: 三类的题量下限（闸门按这个判红；作者要求 18~22 道）
MIN_PER_CLASS = {"局势": 8, "决策": 5, "规则": 6}
TOTAL_MIN, TOTAL_MAX = 18, 22


def class_counts(bank: list[Q]) -> dict[str, int]:
    """按 J / Z2 / R 三类数题量（`category` 分别是 局势 / 决策 / 规则）。"""
    out: dict[str, int] = {k: 0 for k in MIN_PER_CLASS}
    for q in bank:
        if q.category in out:
            out[q.category] += 1
    return out


def build_hard2_bank(board=None) -> list[Q]:
    """出整套第二批难题（J 局势 + Z2 决策 + R 规则）。

    `board` 只为兼容 `exam.py` 的调用习惯（`build_hard_bank(game)` 那种）；
    本题库的板子由每道题自己钉死（座位↔身份一律显式指定），不跟着存档漂。
    """
    VERIFIED.clear()
    NOTES.clear()
    CHECKS.clear()
    R_RECHECK.clear()
    _ = board
    bank: list[Q] = []
    bank += build_j()
    bank += build_z2()
    bank += build_r()
    seen: dict[str, int] = {}
    for q in bank:
        seen[q.qid] = seen.get(q.qid, 0) + 1
    for qid, n in seen.items():
        if n > 1:
            _note(f"题号 {qid} 出现了 {n} 次")
    by = class_counts(bank)
    thin = {c: n for c, n in by.items() if n < MIN_PER_CLASS[c]}
    if thin:
        _note("题量不够：" + "；".join(f"{c} 只有 {n} 道（要 ≥{MIN_PER_CLASS[c]}）"
                                       for c, n in thin.items()))
    if not (TOTAL_MIN <= len(bank) <= TOTAL_MAX):
        _note(f"总题量 {len(bank)} 不在 {TOTAL_MIN}~{TOTAL_MAX} 之间")
    return bank


def notes() -> list[str]:
    """出题过程中记下的问题（闸门与自检都会打印）。"""
    return list(NOTES)


def checks() -> list[tuple[str, str, bool]]:
    """出题过程中做的引擎小验证（`False` = 引擎行为和题库答案不一致）。"""
    return list(CHECKS)


def verified_qids() -> set[str]:
    """最近一次出题里**真的跑过引擎校验**的题号。"""
    return set(VERIFIED)


def recheck_r(qid: str) -> str | None:
    """按题号重算一道 R 题的期望答案（闸门用；引擎改了口径必须变红）。"""
    fn = R_RECHECK.get(qid)
    if fn is None:
        return None
    return str(fn())


def _expect_text(q: Q) -> str:
    """自检打印用：rubric 题打印要点清单，其它题打印期望答案。"""
    if q.grader == "rubric":
        return "要点 " + "、".join(f"「{n}」" for n, _ws in q.rubric)
    return str(q.expect)


def main() -> int:
    bank = build_hard2_bank()
    by = class_counts(bank)
    print("=" * 78)
    print(f"第二批高难度题库：{len(bank)} 道题")
    print("   " + "　".join(f"{c} {by.get(c, 0)} 道" for c in MIN_PER_CLASS))
    open_n = sum(1 for q in bank if getattr(q, "book", "") == "open")
    print(f"   开卷（依赖本项目特设机制）{open_n} 道 / 闭卷（只用官方机制）{len(bank) - open_n} 道；"
          f"全部题的上下文都是 rules:<本局板子>")
